export const repair_receipt_term_versions = sqliteTable("repair_receipt_term_versions", {
  id: integer("id").primaryKey({ autoIncrement: true }),
  public_id: text("public_id").notNull(),
  shop_id: integer("shop_id").notNull(),
  version_number: integer("version_number").notNull(),
  title: text("title").notNull(),
  body_text: text("body_text").notNull(),
  content_sha256: text("content_sha256").notNull(),
  is_active: integer("is_active").notNull().default(1),
  effective_from: text("effective_from").notNull().default(sql`CURRENT_TIMESTAMP`),
  effective_to: text("effective_to"),
  created_by_user_id: integer("created_by_user_id").notNull(),
  created_at: text("created_at").notNull().default(sql`CURRENT_TIMESTAMP`),
}, (t) => [
  uniqueIndex("repair_receipt_term_versions_public_unique").on(t.public_id),
  uniqueIndex("repair_receipt_term_versions_shop_version_unique").on(t.shop_id,t.version_number),
  uniqueIndex("repair_receipt_term_versions_scope_id_unique").on(t.shop_id,t.id),
  index("repair_receipt_term_versions_active_idx").on(t.shop_id,t.is_active,t.effective_from),
  foreignKey({columns:[t.shop_id],foreignColumns:[repair_shops.id]}).onDelete("restrict"),
  foreignKey({columns:[t.shop_id,t.created_by_user_id],foreignColumns:[tamiran_users.shop_id,tamiran_users.id]}).onDelete("restrict"),
  check("repair_receipt_term_versions_version",sql`typeof("version_number")='integer' AND "version_number" BETWEEN 1 AND 65535`),
  check("repair_receipt_term_versions_active",sql`"is_active" IN (0,1)`),
  check("repair_receipt_term_versions_hash",sql`length("content_sha256")=64 AND "content_sha256" NOT GLOB '*[^0-9a-f]*'`),
  check("repair_receipt_term_versions_title",sql`length("title") BETWEEN 1 AND 180`),
  check("repair_receipt_term_versions_public_id",sql`length("public_id") BETWEEN 1 AND 26`),
]);

